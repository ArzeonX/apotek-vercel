def fuzzifikasi_nilai(nilai):
    rendah = Segitiga(0, 0, 2)
    sedang = Segitiga(1.5, 2.5, 3.5)
    tinggi = Segitiga(3, 4, 4)

    miu_rendah = rendah.hitung(nilai)
    miu_sedang = sedang.hitung(nilai)
    miu_tinggi = tinggi.hitung(nilai)

    return {
        'rendah': miu_rendah,
        'sedang': miu_sedang,
        'tinggi': miu_tinggi
    }

def fuzzifikasi_pendapatan(pendapatan):
    rendah = Trapesium(0, 0, 2.5, 4)
    sedang = Trapesium(2, 6, 9, 13)
    tinggi = Trapesium(10, 13, 20, 20)


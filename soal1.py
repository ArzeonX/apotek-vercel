def L(x, alpha, beta):
    if x <= alpha:
        return 1.0
    elif x <= beta:
        return (beta - x) / (beta - alpha)
    else:
        return 0.0

def R(x, alpha, beta):
    if x <= alpha:
        return 0.0
    elif x <= beta:
        return (x - alpha) / (beta - alpha)
    else:
        return 1.0


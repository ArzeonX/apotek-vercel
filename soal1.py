    print(f"Beasiswa Sedikit (μ) = {hasil_sedikit:.2f}")
    print(f"Beasiswa Banyak (μ) = {hasil_banyak:.2f}")
    hasil_beasiswa = defuzzifikasi_centroid(x_beasiswa, miu_sedikit, miu_banyak, hasil_sedikit, hasil_banyak)
    print(f"\nHasil Defuzzifikasi (Metode Centroid): {hasil_beasiswa:.2f}")
    print(f"\nHasil Defuzzifikasi (Metode Centroid): {hasil_beasiswa:.2f}")


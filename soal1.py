import numpy as np
import matplotlib.pyplot as plt

class Segitiga:
    def __init__(self, alpha, beta, gamma):
        self.alpha = alpha
        self.beta = beta
        self.gamma = gamma

    def hitung(self, x):
        if x <= self.alpha:
            return 0
        elif self.alpha < x <= self.beta:
            return (x - self.alpha) / (self.beta - self.alpha)
        elif self.beta < x <= self.gamma:
            return (self.gamma - x) / (self.gamma - self.beta)
        else:
            return 0

class Trapesium:
    def __init__(self, alpha, beta, gamma, delta):
        self.alpha = alpha
        self.beta = beta
        self.gamma = gamma
        self.delta = delta

    def hitung(self, x):
        if x <= self.alpha:
            return 0
        elif self.alpha < x <= self.beta:
            return (x - self.alpha) / (self.beta - self.alpha)
        elif self.beta < x <= self.gamma:
            return 1
        elif self.gamma < x <= self.delta:
            return (self.delta - x) / (self.delta - self.gamma)
        else:
            return 0

class SFunction:
    def __init__(self, alpha, beta, gamma):
        self.alpha = alpha
        self.beta = beta
        self.gamma = gamma

    def hitung(self, x):
        if x <= self.alpha:
            return 0
        elif self.alpha < x <= self.beta:
            return 2 * ((x - self.alpha) / (self.gamma - self.alpha)) ** 2
        elif self.beta < x <= self.gamma:
            return 1 - 2 * ((x - self.gamma) / (self.gamma - self.alpha)) ** 2
        else:
            return 1

class GaussianFunction:
    def __init__(self, m, sigma):
        self.m = m
        self.sigma = sigma

    def hitung(self, x):
        return np.exp(-((x - self.m) ** 2) / (2 * self.sigma ** 2))


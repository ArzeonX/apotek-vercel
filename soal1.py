    plt.plot(x_beasiswa, miu_sedikit, 'b--', label='Beasiswa Sedikit')
    plt.plot(x_beasiswa, miu_banyak, 'g--', label='Beasiswa Banyak')

    truncated_sedikit = np.minimum(miu_sedikit, np.ones_like(miu_sedikit) * hasil_sedikit)

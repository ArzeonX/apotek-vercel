    plt.fill_between(x_beasiswa, truncated_banyak, alpha=0.3, color='green')

    plt.axvline(x=hasil_beasiswa, color='red', linestyle='-', label=f'Hasil ({hasil_beasiswa:.2f})')
    plt.xlabel('Beasiswa')
    plt.ylabel('Membership')
    plt.title('Hasil Inferensi Fuzzy Mamdani')
    plt.legend()
    plt.grid()
    plt.show()

    return hasil_beasiswa
